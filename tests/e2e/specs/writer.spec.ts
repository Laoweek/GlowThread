import { test, expect, PAGES, postComment, toast, unique } from './fixtures'

test.describe('logged-in member', () => {
  test('posts a comment with the mouse', async ({ wiki }) => {
    await wiki.as('Alice')
    await wiki.open(PAGES.play)
    const s = wiki.section
    const count = Number(await s.locator('#gt-heading .gt-num').textContent())
    const box = s.getByRole('textbox')
    await box.click()
    const send = s.getByRole('button', { name: 'Send' })
    await expect(send).toBeDisabled()
    const text = unique('Test comment')
    await box.fill(text)
    await expect(send).toBeEnabled()
    await send.click()
    // New comments go first (after any pinned ones), in both orders.
    const mine = s.locator('ol > li article', { hasText: text })
    await expect(mine).toHaveCount(1)
    await expect(s.locator('ol > li > article:not([data-pinned])').first()).toContainText(text)
    await expect(box).toHaveValue('')
    await expect(s.locator('#gt-heading .gt-num')).toHaveText(String(count + 1))
    // It survives a reload: the server has it.
    await wiki.open(PAGES.play)
    await wiki.section.getByRole('tab', { name: 'Newest' }).click()
    await expect(wiki.section.locator('article', { hasText: text })).toHaveCount(1)
  })

  test('posts with the keyboard only', async ({ wiki, page }) => {
    test.skip(wiki.phone, 'keyboard path is checked on desktop')
    await wiki.as('Bob')
    await wiki.open(PAGES.play)
    const box = wiki.section.getByRole('textbox')
    // Tab from the sort tabs into the composer.
    await wiki.section.getByRole('tab', { name: 'Top' }).focus()
    for (let i = 0; i < 6 && !(await box.evaluate((el) => el === document.activeElement)); i++) await page.keyboard.press('Tab')
    await expect(box).toBeFocused()
    const text = unique('Sent from the keyboard')
    await page.keyboard.type(text)
    await page.keyboard.press('Control+Enter')
    await expect(wiki.section.locator('article', { hasText: text })).toHaveCount(1)
  })

  test('replies inline, addressed to the person', async ({ wiki }) => {
    const parent = await postComment(wiki, 'Admin', PAGES.play, unique('Waiting for a reply'))
    await wiki.as('Carol')
    await wiki.open(PAGES.play)
    await wiki.section.getByRole('tab', { name: 'Newest' }).click()
    const article = wiki.section.locator('article[data-comment="' + parent + '"]')
    await article.getByRole('button', { name: 'Reply' }).first().click()
    const box = article.getByRole('textbox')
    await expect(box).toBeFocused()
    await expect(box).toHaveAttribute('placeholder', 'Reply to @Admin')
    const text = unique('Reply text')
    await box.fill(text)
    await article.getByRole('button', { name: 'Send' }).click()
    await expect(article.locator('article', { hasText: text })).toHaveCount(1)
    await expect(article.getByRole('textbox')).toHaveCount(0)
  })

  test('likes and takes the like back, at once', async ({ wiki, page }) => {
    const id = await postComment(wiki, 'Admin', PAGES.play, unique('Like this one'))
    await wiki.as('Alice')
    await wiki.open(PAGES.play)
    await wiki.section.getByRole('tab', { name: 'Newest' }).click()
    const like = wiki.section.locator('article[data-comment="' + id + '"] footer button[aria-pressed]').first()
    await expect(like).toHaveAttribute('aria-pressed', 'false')
    await like.click()
    await expect(like).toHaveAttribute('aria-pressed', 'true')
    await expect(like).toHaveText('1')
    await page.waitForLoadState('networkidle')
    await like.click()
    await expect(like).toHaveAttribute('aria-pressed', 'false')
    await expect(like).toHaveText('0')
    await page.waitForLoadState('networkidle')
    const s = await wiki.api('Admin')
    const list = await s.rest('/page/' + (await wiki.pageId(PAGES.play)) + '/comments?sort=new')
    expect(list.comments.find((c: any) => c.id === id).likes).toBe(0)
  })

  test('reports with a reason', async ({ wiki, page }) => {
    // The reporter is a sysop: regular accounts may report 20 times a day, and repeated
    // test runs would use that up (the menu then has no Report item).
    const id = await postComment(wiki, 'Admin', PAGES.play, unique('A comment to report'))
    await wiki.as('Moderator')
    await wiki.open(PAGES.play)
    await wiki.section.getByRole('tab', { name: 'Newest' }).click()
    const article = wiki.section.locator('article[data-comment="' + id + '"]')
    await article.getByRole('button', { name: 'More actions' }).first().click()
    await page.getByRole('menuitem', { name: 'Report' }).click()
    const form = wiki.phone ? page.getByRole('dialog', { name: 'Report comment' }) : page.locator('#glowthread-portal form')
    await expect(form).toBeVisible()
    const submit = form.getByRole('button', { name: 'Send report' })
    await expect(submit).toBeDisabled()
    await form.getByRole('radio', { name: 'Off topic' }).click()
    await form.getByRole('textbox').fill('Test report')
    await submit.click()
    await expect(toast(page)).toContainText('Thanks, the moderators will take a look')
    await article.getByRole('button', { name: 'More actions' }).first().click()
    await expect(page.getByRole('menuitem', { name: 'Reported' })).toHaveAttribute('data-disabled', '')
    await page.keyboard.press('Escape')
  })

  test('deletes an own comment after confirming in place', async ({ wiki, page }) => {
    const text = unique('A comment to delete')
    const id = await postComment(wiki, 'Bob', PAGES.play, text)
    await wiki.as('Bob')
    await wiki.open(PAGES.play)
    await wiki.section.getByRole('tab', { name: 'Newest' }).click()
    const article = wiki.section.locator('article[data-comment="' + id + '"]')
    await article.getByRole('button', { name: 'More actions' }).first().click()
    await page.getByRole('menuitem', { name: 'Delete' }).click()
    const confirm = article.getByRole('group', { name: 'Delete this comment? This cannot be undone.' })
    await expect(confirm).toBeVisible()
    await confirm.getByRole('button', { name: 'Delete' }).click()
    await expect(wiki.section.locator('article[data-comment="' + id + '"]')).toHaveCount(0)
    await expect(toast(page)).toContainText('Comment deleted')
  })

  test('suggests people to @mention and inserts the name', async ({ wiki, page }) => {
    await wiki.as('Alice')
    await wiki.open(PAGES.showcase)
    const box = wiki.section.getByRole('textbox')
    await box.click()
    await page.keyboard.type('Thanks @Bo')
    const list = page.getByRole('listbox', { name: 'People you can mention' })
    await expect(list.getByRole('option', { name: 'Bob' })).toBeVisible()
    await expect(box).toHaveAttribute('aria-activedescendant', /mentions-0$/)
    await page.keyboard.press('Enter')
    await expect(box).toHaveValue('Thanks @Bob ')
    await expect(list).toHaveCount(0)
    // The emoji picker inserts at the caret.
    await wiki.section.getByRole('button', { name: 'Emoji' }).click()
    await page.getByRole('button', { name: '🎂' }).click()
    await expect(box).toHaveValue('Thanks @Bob 🎂')
    await expect(box).toBeFocused()
    await box.fill('')
  })

  test('a posted @mention links to the user page', async ({ wiki }) => {
    // A mention is stored as <@ID> (docs/api.md, "Input rules") and shows the current name.
    // Typed "@Name" is plain text: mentions.spec.ts has the composer side.
    const r = await (await wiki.api('Admin')).api({ action: 'query', list: 'users', ususers: 'Carol' })
    const id = await postComment(wiki, 'Admin', PAGES.play, unique('Ask <@' + r.query.users[0].userid + '> about rye, not @Carol'))
    await wiki.as('Alice')
    await wiki.open(PAGES.play)
    await wiki.section.getByRole('tab', { name: 'Newest' }).click()
    const links = wiki.section.locator('article[data-comment="' + id + '"] p a')
    await expect(links).toHaveCount(1)
    await expect(links).toHaveText('@Carol')
    await expect(links).toHaveAttribute('href', /User:Carol$/)
  })
})
